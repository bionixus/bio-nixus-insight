/**
 * Rewrites the Organization JSON-LD block in index.html from
 * buildCanonicalOrganization() so there is exactly one source of truth.
 *
 * The block was previously hand-maintained and had drifted from
 * src/lib/seo/organization.ts (different description, different knowsAbout,
 * fewer addresses). Two conflicting definitions of the same @id is an
 * entity-resolution risk for search engines and AI crawlers.
 *
 * Runs in prebuild. Use --check in CI to fail instead of writing.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { tmpdir } from 'os';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const indexHtmlPath = join(root, 'index.html');

const START_MARKER = '<!-- org-schema:start (generated by scripts/sync-org-schema.mjs) -->';
const END_MARKER = '<!-- org-schema:end -->';

const outfile = join(tmpdir(), `org-schema-${Date.now()}.mjs`);

await build({
  entryPoints: [join(root, 'src/lib/seo/organization.ts')],
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  alias: { '@': join(root, 'src') },
  logLevel: 'silent',
});

const { buildCanonicalOrganization } = await import(pathToFileURL(outfile).href);

const org = buildCanonicalOrganization('en');
const block = [
  START_MARKER,
  `    <script type="application/ld+json">${JSON.stringify(org)}</script>`,
  `    ${END_MARKER}`,
].join('\n    ');

const html = readFileSync(indexHtmlPath, 'utf8');

const startIdx = html.indexOf(START_MARKER);
const endIdx = html.indexOf(END_MARKER);
if (startIdx === -1 || endIdx === -1) {
  console.error(
    `[sync-org-schema] Markers not found in index.html. Expected:\n  ${START_MARKER}\n  ${END_MARKER}`,
  );
  process.exit(1);
}

const before = html.slice(0, startIdx);
const after = html.slice(endIdx + END_MARKER.length);
const next = `${before}${block.trimEnd()}${after}`;

if (next === html) {
  console.log('[sync-org-schema] index.html Organization block already in sync.');
  process.exit(0);
}

if (process.argv.includes('--check')) {
  console.error(
    '[sync-org-schema] index.html Organization block is out of sync with organization.ts. Run: npm run sync:org-schema',
  );
  process.exit(1);
}

writeFileSync(indexHtmlPath, next, 'utf8');
console.log(
  `[sync-org-schema] Regenerated index.html Organization block (${JSON.stringify(org).length} bytes).`,
);
