/**
 * Generates src/routes/lazySeoPages.ts (+ .ssr.ts) from the remaining eager
 * `@/pages/*` imports in routes.tsx and the template route builders.
 * Run: node scripts/generate-lazy-seo-pages.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const routesPath = path.join(root, 'src/routes.tsx');
const routesSrc = fs.readFileSync(routesPath, 'utf8');

const TEMPLATE_PAGES = [
  ['CompanyDirectoryPage', '@/pages/templates/CompanyDirectoryPage'],
  ['DirectoryHubPage', '@/pages/templates/DirectoryHubPage'],
  ['IndustryCountryBofuPage', '@/pages/templates/IndustryCountryBofuPage'],
  ['TopIndustryMarketResearchListicle', '@/pages/templates/TopIndustryMarketResearchListicle'],
  ['CompetitorAlternativePage', '@/pages/templates/CompetitorAlternativePage'],
  ['ArPharmaCompaniesDirectoryPage', '@/pages/templates/ArPharmaCompaniesDirectoryPage'],
  ['CountryKeywordPage', '@/pages/templates/CountryKeywordPage'],
  ['DevelopedMarketMedtechPage', '@/pages/templates/DevelopedMarketMedtechPage'],
  ['DevelopedMarketMedtechListiclePage', '@/pages/templates/DevelopedMarketMedtechListiclePage'],
  ['SpecialtyMarketDemandPage', '@/pages/templates/SpecialtyMarketDemandPage'],
];

/** Already code-split; do not duplicate. */
const SKIP_DEFAULTS = new Set([
  'BlogPostPage', // same module as lazyReportPages BlogPost
  'Index',
]);

const pages = new Map(); // exportName -> { specifier, namedFrom? }

const defaultImportRe = /^import (\w+) from '(@\/pages\/[^']+)';$/gm;
let match;
while ((match = defaultImportRe.exec(routesSrc))) {
  const [, name, specifier] = match;
  if (SKIP_DEFAULTS.has(name)) continue;
  pages.set(name, { specifier });
}

for (const [name, specifier] of TEMPLATE_PAGES) {
  pages.set(name, { specifier });
}

pages.set('TopConsumerInsightsCompaniesKsa2026', {
  specifier: '@/pages/TopConsumerInsightsCompaniesKsa2026',
});

const named = {
  exportName: 'TopConsumerInsightsCompaniesSaudiArabiaRedirect',
  specifier: '@/pages/TopConsumerInsightsCompaniesKsa2026',
  namedExport: 'TopConsumerInsightsCompaniesSaudiArabiaRedirect',
};

const sorted = [...pages.entries()].sort(([a], [b]) => a.localeCompare(b));

const clientLines = [
  '/**',
  ' * Client-side code-split for remaining marketing / SEO pages (React.lazy).',
  ' * SSR uses lazySeoPages.ssr.ts (eager) via the Vite `ssr-route-split` plugin.',
  ' * Regenerated by scripts/generate-lazy-seo-pages.mjs',
  ' */',
  "import { lazy } from 'react';",
  '',
];

const ssrLines = [
  '/**',
  ' * SSR-only eager imports paired with lazySeoPages.ts.',
  ' * Regenerated by scripts/generate-lazy-seo-pages.mjs',
  ' */',
  '',
];

for (const [name, { specifier }] of sorted) {
  clientLines.push(`export const ${name} = lazy(() => import('${specifier}'));`);
  ssrLines.push(`export { default as ${name} } from '${specifier}';`);
}

clientLines.push(
  `export const ${named.exportName} = lazy(() =>`,
  `  import('${named.specifier}').then((m) => ({ default: m.${named.namedExport} })),`,
  ');',
);
ssrLines.push(
  `export { ${named.namedExport} } from '${named.specifier}';`,
  '',
  '/** SSR pages are eager via this barrel; client preload maps live in lazySeoPages.ts. */',
  'export function getSeoPageLoader(_pathname: string): undefined {',
  '  return undefined;',
  '}',
);

const loaderEntries = sorted.map(
  ([name, { specifier }]) => `  ${JSON.stringify(name)}: () => import('${specifier}'),`,
);
loaderEntries.push(
  `  ${JSON.stringify(named.exportName)}: () => import('${named.specifier}'),`,
);

const pathToName = new Map();
const routeRe =
  /\{\s*path:\s*'([^']+)'\s*,\s*element:\s*(?:suspensePage\()?<(\w+)/g;
while ((match = routeRe.exec(routesSrc))) {
  const [, routePath, exportName] = match;
  if (pages.has(exportName) || exportName === named.exportName) {
    pathToName.set(routePath, exportName);
  }
}

const pathEntries = [...pathToName.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([routePath, exportName]) => `  ${JSON.stringify(routePath)}: ${JSON.stringify(exportName)},`);

clientLines.push(
  '',
  'const seoPageLoaders: Record<string, () => Promise<unknown>> = {',
  ...loaderEntries,
  '};',
  '',
  'const seoPathToExport: Record<string, string> = {',
  ...pathEntries,
  '};',
  '',
  'export function getSeoPageLoader(pathname: string): (() => Promise<unknown>) | undefined {',
  "  const normalized = pathname.replace(/\\/$/, '') || '/';",
  '  const exportName = seoPathToExport[normalized] ?? seoPathToExport[pathname];',
  '  return exportName ? seoPageLoaders[exportName] : undefined;',
  '}',
  '',
);

fs.writeFileSync(path.join(root, 'src/routes/lazySeoPages.ts'), clientLines.join('\n'));
fs.writeFileSync(path.join(root, 'src/routes/lazySeoPages.ssr.ts'), `${ssrLines.join('\n')}\n`);

const pageImportLine = /^import \w+ from '@\/pages\/[^']+';\n/gm;
const namedPageImport = /^import \w+,\s*\{[\s\S]*?}\s*from '@\/pages\/[^']+';\n/m;
const withoutPageImports = routesSrc.replace(namedPageImport, '').replace(pageImportLine, '');

const exportNames = [...sorted.map(([name]) => name), named.exportName].sort((a, b) =>
  a.localeCompare(b),
);
const chunkSize = 4;
const importChunks = [];
for (let i = 0; i < exportNames.length; i += chunkSize) {
  importChunks.push(`  ${exportNames.slice(i, i + chunkSize).join(', ')},`);
}

const barrelImport = `import {\n${importChunks.join('\n')}\n} from '@/routes/lazySeoPages';\n`;

const marker = "from '@/routes/lazyReportPages';\n";
const markerIdx = withoutPageImports.indexOf(marker);
if (markerIdx === -1) {
  throw new Error('Could not find lazyReportPages import marker');
}
const insertAt = markerIdx + marker.length;
const next = `${withoutPageImports.slice(0, insertAt)}${barrelImport}${withoutPageImports.slice(insertAt)}`;

const withBlogAlias = next.replace(
  'element: <BlogPostPage fixedSlug={SKYRIZI_ROOT_SLUG} />',
  'element: suspensePage(<BlogPost fixedSlug={SKYRIZI_ROOT_SLUG} />)',
);

fs.writeFileSync(routesPath, withBlogAlias);

console.log(`Wrote ${sorted.length + 1} lazy SEO page exports and ${pathToName.size} preload paths`);
